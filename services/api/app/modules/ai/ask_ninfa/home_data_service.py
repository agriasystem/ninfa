"""HomeDataService: the safe, read-only SEMANTIC data layer behind Mia Home (Mia V2).

    QuestionResolution  ->  deterministic facts (sections)  ->  OperationalContext

A hotel owner asks "Gli OTA sono a posto?" or "Qual è l'occupazione dei prossimi 7 giorni?". The
answer needs numbers the Decision Feed does not carry (the OTA share when no decision fired, the
occupancy of next week). This service is where they come from - and the ONLY place:

- **Never the model.** No SQL is generated by the model, no table is exposed to it, no arbitrary
  internal API is callable by it. Every figure here is read from a stored snapshot, from an existing
  detector service (`OtaDependencyService`, read-only) or is a plain sum/ratio computed below.
- **No raw records leave this module.** What is returned are small labelled sections ("Occupazione
  sulle prenotazioni attuali: 62,50 %"), never booking rows, guest data, ids or SQL.
- **No new business definition.** Only metrics the repository already defines: `BookingSnapshot`
  (rooms/bookings/revenue/occupancy "on the books"), the OTA dependency evaluation and its channel
  rules (Gate 9). What is NOT defined (fatturato, RevPAR, cancellations, cost/labour figures when no
  decision fired, ...) is reported as "not available" - see `home_facts.UNSUPPORTED_NOTES`.
- **Scoped.** Every query goes through the repositories of the request's `TenantContext` and the
  property resolved by the route; the booking data source is the EXACT one the analysis run recorded
  in its provenance (never guessed, never another property's).
- **The run is the authority.** A decision exists only if the persisted run produced it. Live reads
  (the OTA share) only ADD metrics; they never create, confirm or contradict a decision.

Every section is anchored to the analysis day (`as_of_local_date`): the stored snapshots of that day
describe the nights from the analysis forward ("sulle prenotazioni attuali"), which is exactly how
the answer must be worded - it is not a forecast and not the final occupancy.
"""

